"""Builds the brand web assets from qt_logo.png.

The source is a 1000x1000 PNG holding a two-line lockup on a black plate:

    line 1  y=346..476   "Q" symbol (x 65..199) + QUANTUM DEVS wordmark
    line 2  y=511..639   tagline

Everything is derived from that one file, with no recolouring: the art is white on
black. The black plate is made transparent for the web assets, because the hero
sits on top of the aurora glow and the grid.

    qt_logo_wide.png   the full lockup, tight-cropped, transparent plate (hero)
    qt_logo_mark.png   the "Q" alone, transparent plate (topbar + favicon)
    qt_logo.ico        NOT generated by default - yours wins; see --make-ico

Run from the project root:
    .venv\\Scripts\\python.exe tools_make_logo_assets.py
    .venv\\Scripts\\python.exe tools_make_logo_assets.py --make-ico
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

BASE = Path(__file__).resolve().parent
SOURCE = BASE / "qt_logo.png"

WIDE_OUT = BASE / "qt_logo_wide.png"
MARK_OUT = BASE / "qt_logo_mark.png"
ICO_OUT = BASE / "qt_logo.ico"

# Measured ink bounding boxes in the 1000x1000 source.
LOCKUP_BOX = (65, 346, 944, 640)  # 879 x 294
Q_BOX = (65, 346, 199, 476)  # 135 x 131, the "Q" glyph alone

MARK_SIZE = 512
ICO_SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]

# Luminance ramp that drops the black plate without eating the artwork. The hero
# sits on top of the aurora glow and the grid, so an opaque plate would show up
# as a black box right where the glow is brightest.
BLACK_START = 6
BLACK_END = 30


def _alpha_from_luminance(image: Image.Image) -> Image.Image:
    rgba = image.convert("RGBA")
    pixels = rgba.load()
    width, height = rgba.size
    span = max(1, BLACK_END - BLACK_START)
    for y in range(height):
        for x in range(width):
            red, green, blue, _ = pixels[x, y]
            luminance = (red * 299 + green * 587 + blue * 114) // 1000
            if luminance <= BLACK_START:
                alpha = 0
            elif luminance >= BLACK_END:
                alpha = 255
            else:
                alpha = round((luminance - BLACK_START) / span * 255)
            pixels[x, y] = (red, green, blue, alpha)
    return rgba


def _pad_to_square(image: Image.Image) -> Image.Image:
    """Centre the crop on a square canvas, keeping an existing alpha channel."""
    width, height = image.size
    if width == height:
        return image
    side = max(width, height)
    offset = ((side - width) // 2, (side - height) // 2)
    if image.mode == "RGBA":
        square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        square.paste(image, offset)
    else:
        square = Image.new("RGB", (side, side), (0, 0, 0))
        square.paste(image.convert("RGB"), offset)
    return square


def main() -> int:
    if not SOURCE.exists():
        print(f"[X] source image missing: {SOURCE}")
        return 1

    source = Image.open(SOURCE).convert("RGB")

    # Web assets: black plate made transparent so the aurora glow and grid show
    # through behind the logo.
    wide = _alpha_from_luminance(source.crop(LOCKUP_BOX))
    wide.save(WIDE_OUT, "PNG", optimize=True)
    print(f"[+] {WIDE_OUT.name}  {wide.size[0]}x{wide.size[1]}  (full lockup, transparent plate)")

    mark = _pad_to_square(_alpha_from_luminance(source.crop(Q_BOX)))
    mark = mark.resize((MARK_SIZE, MARK_SIZE), Image.LANCZOS)
    mark.save(MARK_OUT, "PNG", optimize=True)
    print(f"[+] {MARK_OUT.name}  {mark.size[0]}x{mark.size[1]}  (Q, transparent plate)")

    # The .ico is opt-in only. A hand-supplied icon is authoritative, so a plain
    # run must never touch it; --make-ico additionally backs up what it replaces.
    if "--make-ico" not in sys.argv:
        print(f"[.] {ICO_OUT.name} left untouched (pass --make-ico to rebuild it)")
        return 0

    # The Windows icon keeps a solid plate: taskbar backgrounds vary, and an
    # opaque square reads correctly on both light and dark shells. It uses the
    # full QUANTUM DEVS lockup (the same art as the in-app top-left logo),
    # letterboxed onto a square canvas so nothing is cropped.
    plate = _pad_to_square(source.crop(LOCKUP_BOX)).resize((MARK_SIZE, MARK_SIZE), Image.LANCZOS)
    if ICO_OUT.exists():
        backup = ICO_OUT.with_suffix(".ico.bak")
        backup.write_bytes(ICO_OUT.read_bytes())
        print(f"[.] existing {ICO_OUT.name} backed up to {backup.name}")
    plate.save(ICO_OUT, format="ICO", sizes=ICO_SIZES)
    print(f"[+] {ICO_OUT.name}  {len(ICO_SIZES)} sizes  (full lockup on solid black)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
